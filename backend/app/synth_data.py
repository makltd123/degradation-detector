def _lower_first(s: str) -> str:
    if len(s) > 1 and s[0].isupper() and s[1].islower():
        return s[0].lower() + s[1:]
    return s


def _strip_qmark(s: str) -> str:
    return s.rstrip("?!. ") + ("" if s.rstrip().endswith("?") else "")


def _typo_word(word: str, rng: random.Random) -> str:
    if len(word) < 5:
        return word
    i = rng.randint(1, len(word) - 3)
    return word[:i] + word[i + 1] + word[i] + word[i + 2 :]


def _typo_variant(sentence: str, rng: random.Random) -> str:
    words = sentence.split()
    candidates = [i for i, w in enumerate(words) if len(w) >= 5]
    if not candidates:
        return sentence
    for i in rng.sample(candidates, k=min(2, len(candidates))):
        words[i] = _typo_word(words[i].strip("?!.,:;"), rng)
        # знаки препинания при свапе могли потеряться — вернём вопросительный
    out = " ".join(words)
    if sentence.endswith("?") and not out.endswith("?"):
        out += "?"
    return out


def generate_historical_queries(rng_seed: int = 42):
    """~100+ вариаций вопросов вокруг статей БЗ.

    Возвращает list[dict]: question, kb_index (индекс в KNOWLEDGE_BASE), kind.
    """
    rng = random.Random(rng_seed)
    questions = [a["question"] for a in KNOWLEDGE_BASE]
    queries = []

    def add(q, kb_index, kind):
        q = " ".join(q.split())
        queries.append({"question": q, "kb_index": kb_index, "kind": kind})

    # прямые совпадения — половина статей как есть
    for i in range(0, len(questions), 2):
        add(questions[i], i, "direct")

    # вежливые обёртки
    for idx in rng.sample(range(len(questions)), 20):
        w = rng.choice(_POLITENESS)
        tail = questions[idx][:-1] if questions[idx].endswith("?") else questions[idx]
        add(w + _lower_first(tail) + "?", idx, "polite")

    # разговорные префиксы
    for idx in rng.sample(range(len(questions)), 20):
        p = rng.choice(_COLLOQUIAL)
        add(p + questions[idx], idx, "colloquial")

    # опечатки
    for idx in rng.sample(range(len(questions)), 14):
        variant = _typo_variant(questions[idx], rng)
        if variant != questions[idx]:
            add(variant, idx, "typo")

    # нерелевантный контекст перед вопросом
    for idx in rng.sample(range(len(questions)), 18):
        c = rng.choice(_CONTEXT)
        add(c + questions[idx], idx, "context")

    # комбинированные вопросы (две темы сразу)
    pairs = set()
    while len(pairs) < 12:
        a, b = rng.sample(range(len(questions)), 2)
        pairs.add((min(a, b), max(a, b)))
    for a, b in sorted(pairs):
        qa = questions[a][:-1] if questions[a].endswith("?") else questions[a]
        qb = _lower_first(
            questions[b][:-1] if questions[b].endswith("?") else questions[b]
        )
        add(f"{qa}, и ещё сразу — {qb}?", a, "combo")

    return queries
